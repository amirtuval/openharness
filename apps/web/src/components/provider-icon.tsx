/**
 * A provider's mark, inline.
 *
 * Not from the icon set `lucide-react` — it dropped brand icons — and not from a CDN:
 * three small paths are less than the request would cost. The Google mark is the four-color
 * one and Microsoft's is the four squares; GitHub's is monochrome and follows `currentColor`,
 * so it stays legible in the dark theme like every other icon in the app.
 *
 * The mark is decorative: the button it sits in carries the provider's name as text, so the
 * SVG is hidden from assistive technology.
 */
/** The model providers this app has a mark for, and the mark itself. */
type ModelProviderMark = 'anthropic' | 'openai' | 'google' | 'openrouter' | 'mistral' | 'deepseek'

/**
 * A model provider's mark, inline (epic #201, X8).
 *
 * The paths are the ones the brand publishes for itself (simple-icons), drawn at the app's own
 * size in `currentColor` so a mark follows the theme like every other icon here. A provider
 * whose mark could not be confirmed — Groq, Together, xAI, Cerebras and Fireworks at the time
 * of writing — gets a **monogram** instead: the first letter of its name. A wrong logo is
 * worse than a plain one, and the tile's own text carries the name either way.
 *
 * Decorative, like {@link ProviderIcon}: the tile beside it names the provider.
 */
export function ModelProviderIcon({
  provider,
  name,
}: {
  /** The Mastra router id, e.g. `openai`. */
  provider: string
  /** The display name, for the monogram's letter. */
  name: string
}) {
  const path = MODEL_PROVIDER_PATHS[provider as ModelProviderMark]
  if (path === undefined) {
    return (
      <span aria-hidden="true" className="text-[0.7rem] leading-none font-semibold">
        {monogram(name)}
      </span>
    )
  }
  return (
    <svg aria-hidden="true" viewBox="0 0 24 24" fill="currentColor" className="size-4">
      <path d={path} />
    </svg>
  )
}

/** The one letter a mark-less provider shows: its name's first alphanumeric character. */
function monogram(name: string): string {
  return (name.match(/[a-z0-9]/iu)?.[0] ?? '?').toUpperCase()
}

