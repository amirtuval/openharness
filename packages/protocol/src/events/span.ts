import { z } from 'zod'

import { EventIdSchema } from '../ids'
import type { DeepReadonly } from '../readonly'
import { ReasoningEffortRunSchema } from '../reasoning'
import { ModeReferenceSchema } from '../resources/mode'
import { EVENT_TYPES, EventSeqSchema, ProcessedAtSchema, SupersedesSchema } from './common'

/**
 * Span events: observability markers that wrap a model request.
 *
 * Every model request is bracketed by a `span.model_request_start` and a
 * `span.model_request_end` carrying its token usage, so a client can time a request and add
 * up a turn's cost from the log alone. The end event is always written, even when the request
 * was aborted by an interrupt or its span was closed by a recovering brain.
 */

/**
 * Token counts for one model request. Matches Anthropic's `BetaManagedAgentsSpanModelUsage`
 * without its optional `speed` field.
 *
 * The four counters are **disjoint** — no token is counted twice — which is what lets
 * `usageCost` price each at its own rate. In particular `input_tokens` is the **uncached** input,
 * the way Anthropic's own `input_tokens` reads: a provider whose API reports a cache-inclusive
 * input (OpenAI's `prompt_tokens`, a Gemini `promptTokenCount`) has already been normalised by
 * `toModelUsage` in `@openharness/brain` before it reaches here. The real prompt size a request
 * was made with is therefore the three input-side counters summed — the primitive the compaction
 * trigger measures against (epic #277, K2).
 */
export const ModelUsageSchema = z.object({
  /** Prompt-cache write tokens, priced separately from the uncached input (epic #277, K2). */
  cache_creation_input_tokens: z.number().int().nonnegative(),
  /** Prompt-cache read tokens, priced separately from the uncached input (epic #277, K2). */
  cache_read_input_tokens: z.number().int().nonnegative(),
  /** Uncached input tokens consumed by this request — see the note above. */
  input_tokens: z.number().int().nonnegative(),
  /** Output tokens generated by this request. */
  output_tokens: z.number().int().nonnegative(),
})

export type ModelUsage = z.infer<typeof ModelUsageSchema>

/**
 * // extension: why a model request ended without a normal reply.
 *
 * Anthropic's `span.model_request_end` only has `is_error`; openharness adds the reason, which
 * the client and the session store need in order to tell three different situations apart:
 *
 * - `interrupted` — a `user.interrupt` cut the request short. The partial text is stored as
 *   an `agent.message` and the turn still ends with `end_turn`.
 * - `brain_lost` — the brain instance died mid-request. A recovering brain closes the orphaned
 *   span with this, then re-runs the turn.
 * - `model_error` — the model request failed (the `session.error` that follows carries the
 *   detail).
 */
export const SpanErrorTypeSchema = z.enum(['interrupted', 'brain_lost', 'model_error'])

export type SpanErrorType = z.infer<typeof SpanErrorTypeSchema>

/** The `error` of a `span.model_request_end` event. */
export const SpanErrorSchema = z.object({
  type: SpanErrorTypeSchema,
  message: z.string().optional(),
})

export type SpanError = z.infer<typeof SpanErrorSchema>

/**
 * // extension: what a request had to cut to fit (epic #277, K6).
 *
 * `tokens_before` is what the newest item cost, `tokens_after` what the truncated form costs, and
 * the difference is what the omission marker stands for. Both are the characters-per-token
 * estimate — the same measure the budget is checked with — not a provider's report.
 */
export const TruncationSchema = z.object({
  /** The `seq` of the event whose text was shortened — the newest item of the request. */
  seq: EventSeqSchema,
  /** What the item cost before it was cut, in tokens. */
  tokens_before: z.number().int().nonnegative(),
  /** What the truncated item costs, in tokens. */
  tokens_after: z.number().int().nonnegative(),
})

export type Truncation = z.infer<typeof TruncationSchema>

/**
 * // extension: why a request was made, when it is not the chat itself (epic #277, C2).
 *
 * `summary` is the one value today: a request the compaction engine made to summarize history.
 * It exists so the log can tell such a request apart from the chat's own — the size accounting's
 * baseline rule reads it (K2) — and it is a union rather than a boolean so a later kind of
 * internal request is a new member, not a second field.
 */
export const ModelRequestPurposeSchema = z.enum(['summary'])

export type ModelRequestPurpose = z.infer<typeof ModelRequestPurposeSchema>

/**
 * A model request started, and the user events it claims.
 *
 * Since D9 (issue #46) this event is also the *claim*: the request it opens answers exactly
 * the user events its `consumes` lists, so "which user message is still waiting for an answer"
 * is a question a reader answers from the log itself, with no mutable `processed_at` column
 * behind it. A claim is ordinary event data: an event that is already consumed by one span
 * cannot be consumed again, and the store enforces that when the span is appended — atomic and
 * fenced like every other write (phase P2a).
 */
export const ModelRequestStartEventSchema = z.object({
  id: EventIdSchema,
  type: z.literal(EVENT_TYPES.modelRequestStart),
  seq: EventSeqSchema,
  processed_at: ProcessedAtSchema,
  /**
   * // extension: the user events this request claims — the `sevt_` ids of the
   * `user.message` / `user.interrupt` events it folds into the request.
   *
   * Optional only so a log stored before D9 (issue #46) keeps validating: those events carry
   * no list, and a reader falls back to the pre-D9 reading (everything queued when the request
   * started was picked up). Every request the brain appends from phase P3 on carries one — and
   * since P4 an interrupt that ends a request is claimed here on the request's
   * `span.model_request_end` instead of by a request of its own. An empty array claims nothing.
   */
  consumes: z.array(EventIdSchema).optional(),
  /**
   * // extension: the model that served this request, a model id (`provider/model`) —
   * the same spelling as `model.id` on the agent.
   *
   * It is recorded per request rather than read off the agent so that a session which changes
   * models mid-conversation keeps, for every request, the model that actually ran — per-model
   * context budgets and the usage the span end reports are then both attributable. Optional
   * for the D9 transition only, like `consumes` above.
   */
  model: z.string().min(1).optional(),
  /**
   * // extension: the reasoning effort this request was asked for and ran with (#252).
   *
   * Written when the session's log asks for one: `requested` is the effort the newest
   * effort-carrying `user.message` named, and `applied` is what the request actually ran with —
   * the same level, or `null` when the model takes no effort and the provider's default was
   * used. It is recorded per request, like `model`, so a session that changes its effort
   * mid-conversation keeps, for every request, what that request ran with.
   *
   * Absent when nothing was asked for, which is every request of a session that never set an
   * effort — a reader without the field reads the provider's default, exactly as before.
   */
  reasoning_effort: ReasoningEffortRunSchema.optional(),
  /**
   * // extension: the mode this request ran under, and the name it had then (#245, M6).
   *
   * Written when the session's mode was applied to the request: `id` is the mode the log
   * points at and `name` is what it was called when the request ran, recorded per request
   * like `model` so that a later rename or edit does not rewrite history. The resolved model
   * the mode produced is in `model` and its effort in `reasoning_effort`, so the two fields
   * beside this one say what the mode resolved to.
   *
   * Absent for a request that ran without a mode — a plain model chat, or one whose mode was
   * gone by the time the request ran.
   */
  mode: ModeReferenceSchema.optional(),
  /**
   * // extension: the newest message was too big for the model and was shortened (epic #277, K6).
   *
   * Summarizing cannot help when the newest item alone is over the chat model's budget — the
   * newest message has to stay verbatim — so the context strategy caps it to a head and a tail
   * with an omission marker, and records what it cut here so a client can show the user that
   * their message was shortened rather than silently dropped. `seq` is the `seq` of the event
   * that carried the text, and the two token counts are what the item cost before and after.
   *
   * Absent when nothing had to be cut, which is every request whose newest message fits — so a
   * session that never sent an oversized message keeps the span shape it always had.
   */
  truncated: TruncationSchema.optional(),
  /**
   * // extension: a request the compaction engine made to write a summary (epic #277, C2).
   *
   * Marked on the span because a summary request is not part of the chat's own context: its
   * `model_usage` measures the summarizer's prompt, not the chat's, so the size accounting
   * refuses it as a baseline when the next request asks how full the context is (K2). Absent for
   * every ordinary request, and — like `consumes` — optional only so a log stored before the
   * field existed keeps validating.
   */
  purpose: ModelRequestPurposeSchema.optional(),
})

/** A stored `span.model_request_start`, deep-readonly (D9, issue #46). */
export type ModelRequestStartEvent = DeepReadonly<z.infer<typeof ModelRequestStartEventSchema>>

/** @deprecated The plain name is deep-readonly now (D9, issue #46); use {@link ModelRequestStartEvent}. */
export type ImmutableModelRequestStartEvent = ModelRequestStartEvent

/**
 * A model request finished — and, since P4, the claim on any user events the request itself
 * answers that its span start did not already list.
 *
 * `model_request_start_id` points at the matching `span.model_request_start`, which is what
 * lets a brain recovering from a crash find and close the span it inherited.
 */
export const ModelRequestEndEventSchema = z.object({
  id: EventIdSchema,
  type: z.literal(EVENT_TYPES.modelRequestEnd),
  seq: EventSeqSchema,
  processed_at: ProcessedAtSchema,
  /** The `span.model_request_start` this closes. */
  model_request_start_id: EventIdSchema,
  /** Token usage for this request. */
  model_usage: ModelUsageSchema,
  /** Whether the model request resulted in an error. */
  is_error: z.boolean().nullable(),
  /**
   * // extension: why the request failed or was aborted.
   *
   * Written together with `is_error: true`; a request that completed normally has neither.
   * The schema does not enforce that pairing — a consumer that wants the reason should read
   * `error`, and one that only wants a yes/no should read `is_error` — but the server always
   * writes the two consistently.
   */
  error: SpanErrorSchema.optional(),
  /**
   * // extension: the chunk range this span end replaces (D9, issue #46).
   *
   * A request whose streamed chunks will have no `agent.message` of their own — it was
   * interrupted before storing one, it streamed no text at all, or a recovering brain closes
   * it with `brain_lost` after a crash — supersedes the orphaned chunks here instead. See
   * {@link SupersedesSchema} for the range's meaning and who reads it.
   */
  supersedes: SupersedesSchema.optional(),
  /**
   * // extension: the user events this span end claims (P4).
   *
   * A `user.interrupt` that cut an open model request short is answered by the request's end,
   * not by a request of its own — no model was called for it — so the interrupt's ids are
   * claimed here, with the same rules and the same atomic, insert-only claim as
   * {@link ModelRequestStartEventSchema}'s `consumes`. The brain writes the list on an
   * `interrupted` end; for every other outcome it is absent. Optional so a log stored before
   * P4 keeps validating.
   */
  consumes: z.array(EventIdSchema).optional(),
})

/** A stored `span.model_request_end`, deep-readonly (D9, issue #46). */
export type ModelRequestEndEvent = DeepReadonly<z.infer<typeof ModelRequestEndEventSchema>>

/** @deprecated The plain name is deep-readonly now (D9, issue #46); use {@link ModelRequestEndEvent}. */
export type ImmutableModelRequestEndEvent = ModelRequestEndEvent

/** Any stored span event. */
export const SpanEventSchema = z.discriminatedUnion('type', [
  ModelRequestStartEventSchema,
  ModelRequestEndEventSchema,
])

/** Any stored span event, deep-readonly (D9, issue #46). */
export type SpanEvent = DeepReadonly<z.infer<typeof SpanEventSchema>>
